"""Harbor-style task/trial/verifier schemas.

A Task bundles an instruction, an environment spec, and a verifier (the
Harbor "task-and-trial" abstraction). A Trial is one execution of a Task
against a specific agent version. Verifiers can be deterministic (a script
that checks exit codes / file state) or LLM-as-judge (scored against a
calibration set so the judge itself is sanity-checked, not trusted blindly).
"""
from __future__ import annotations

import enum
import uuid
from datetime import datetime
from typing import Any, Literal

from pydantic import BaseModel, Field, field_validator


class VerifierKind(str, enum.Enum):
    DETERMINISTIC = "deterministic"
    LLM_JUDGE = "llm_judge"


class DeterministicVerifierSpec(BaseModel):
    kind: Literal[VerifierKind.DETERMINISTIC] = VerifierKind.DETERMINISTIC
    # shell command run inside the sandbox; exit code 0 == pass
    check_command: str
    timeout_seconds: int = 30


class LLMJudgeVerifierSpec(BaseModel):
    kind: Literal[VerifierKind.LLM_JUDGE] = VerifierKind.LLM_JUDGE
    rubric: str
    # calibration examples: (trajectory_summary, expected_verdict) so the
    # judge's reliability can be measured before it's trusted on live trials
    calibration_set: list[tuple[str, bool]] = Field(default_factory=list)
    pass_threshold: float = 0.7


VerifierSpec = DeterministicVerifierSpec | LLMJudgeVerifierSpec


class EnvironmentSpec(BaseModel):
    """What a trial runs inside. Mirrors NeMo-Gym's separation of dataset /
    harness / verifier / state: this is the 'state' + sandbox shape part."""

    image: str = "python:3.11-slim"
    setup_commands: list[str] = Field(default_factory=list)
    files: dict[str, str] = Field(default_factory=dict)  # path -> content
    env_vars: dict[str, str] = Field(default_factory=dict)
    max_runtime_seconds: int = 300


class FailureClusterOrigin(BaseModel):
    """Provenance: which production failure cluster produced this task, if
    the task was auto-generated by the mining service rather than hand-written."""

    cluster_id: str
    source_trace_ids: list[str]
    discovered_at: datetime
    cluster_size: int
    representative_summary: str


class Task(BaseModel):
    id: uuid.UUID = Field(default_factory=uuid.uuid4)
    name: str
    category: str
    instruction: str
    environment: EnvironmentSpec
    verifier: VerifierSpec
    origin: FailureClusterOrigin | None = None
    created_at: datetime = Field(default_factory=datetime.utcnow)
    approved: bool = False  # auto-generated tasks require back-office approval

    @field_validator("name")
    @classmethod
    def _non_empty_name(cls, v: str) -> str:
        if not v.strip():
            raise ValueError("task name must not be empty")
        return v


class TrialStatus(str, enum.Enum):
    PENDING = "pending"
    RUNNING = "running"
    PASSED = "passed"
    FAILED = "failed"
    ERRORED = "errored"  # infra failure, not an agent failure
    TIMED_OUT = "timed_out"


class Trial(BaseModel):
    id: uuid.UUID = Field(default_factory=uuid.uuid4)
    task_id: uuid.UUID
    agent_version: str
    seed: int
    status: TrialStatus = TrialStatus.PENDING
    sandbox_id: str | None = None
    started_at: datetime | None = None
    finished_at: datetime | None = None
    verifier_output: dict[str, Any] = Field(default_factory=dict)
    retries: int = 0
    trace_url: str | None = None  # LangSmith trace link for this trial

    @property
    def passed(self) -> bool:
        return self.status == TrialStatus.PASSED


class RegressionRun(BaseModel):
    """A full nightly/pre-deploy run: one set of tasks x two agent versions,
    paired by (task_id, seed) so the statistical comparison in stats/significance.py
    can treat them as matched pairs."""

    id: uuid.UUID = Field(default_factory=uuid.uuid4)
    baseline_version: str
    candidate_version: str
    task_ids: list[uuid.UUID]
    seeds_per_task: int = 5
    created_at: datetime = Field(default_factory=datetime.utcnow)
    trial_ids: list[uuid.UUID] = Field(default_factory=list)
